-- 문의 기능 폐기 — inquiry 테이블 제거 (2026-08-07)
--
-- schema.sql은 최초 생성 전용(재실행 불가)이라, 이미 스키마가 깔린 DB(배포 DB·기존 로컬)에는 이 파일을 적용한다.
-- schema.sql에서도 같은 테이블을 뺐으므로 신규 DB와 최종 상태가 같다.
--
-- 폐기 범위: 접수(I-5)·조회(M-9)·관리자 답변(AD-1·AD-2)·문의 챗봇(CH-3)이 한꺼번에 폐기됐다.
-- 넣는 쪽도 보는 쪽도 없어져 테이블만 남으면 죽은 스키마가 된다.
--
-- 되돌릴 수 없다 — 시드로 넣은 데모 문의 2건이 함께 사라진다. 운영 데이터는 없다(접수 경로가
-- 문의 챗봇뿐이었고 그 챗봇이 구현된 적이 없다).
--
-- inquiry는 member를 참조하기만 하고 참조당하지 않으므로, 다른 테이블의 FK를 먼저 손댈 필요가 없다.

DROP TABLE IF EXISTS inquiry;
