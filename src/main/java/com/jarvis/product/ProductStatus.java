package com.jarvis.product;

/**
 * 상품이 누구에게 보이는가 — 소비자/판매자 두 축을 한 값으로 표현한다.
 *
 * <p>{@code HIDDEN}과 {@code DELETED}는 소비자에겐 똑같이 "판매자가 내림"이지만 판매자 화면에서
 * 갈린다: 숨김은 자기 목록에 남아 되돌릴 수 있고, 삭제는 목록에서도 사라지고 되돌릴 수 없다.
 * 하드 삭제는 하지 않는다 — 주문 내역·매출 통계가 상품을 계속 참조하기 때문이다.
 */
public enum ProductStatus {

    ON_SALE,
    /** 판매자가 내림 — 판매자 목록엔 남는다 */
    HIDDEN,
    /** 판매자가 삭제 — 판매자에게도 보이지 않고 상태를 되돌릴 수 없다 (I-12 전용 전이) */
    DELETED
}
